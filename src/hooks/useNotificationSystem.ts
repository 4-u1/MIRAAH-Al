import { useState, useEffect, useMemo, useCallback } from "react";
import { AssetRecord, AppNotification, Finding, ActionItem } from "../types";
import { playNotificationSound } from "../utils/audioAlert";

const STORAGE_KEY = "miraah_notifications_v1";
const SOUND_KEY = "miraah_notification_sound_enabled";

export function useNotificationSystem(
  assets: AssetRecord[],
  onNavigateTab: (tabId: string) => void,
  onSelectAsset?: (assetId: string) => void,
  onHighlightFinding?: (findingId: number) => void
) {
  const [notifications, setNotifications] = useState<AppNotification[]>([]);
  const [activeToasts, setActiveToasts] = useState<AppNotification[]>([]);
  const [soundEnabled, setSoundEnabled] = useState<boolean>(() => {
    try {
      const saved = localStorage.getItem(SOUND_KEY);
      return saved !== null ? JSON.parse(saved) : true;
    } catch {
      return true;
    }
  });

  const [dismissedIds, setDismissedIds] = useState<Set<string>>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY + "_dismissed");
      return saved ? new Set(JSON.parse(saved)) : new Set();
    } catch {
      return new Set();
    }
  });

  const [readIds, setReadIds] = useState<Set<string>>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY + "_read");
      return saved ? new Set(JSON.parse(saved)) : new Set();
    } catch {
      return new Set();
    }
  });

  // Track simulated items
  const [extraNotifications, setExtraNotifications] = useState<AppNotification[]>([]);

  // Build baseline notifications dynamically from current assets data (High Risk findings & approaching deadlines)
  const autoGeneratedNotifications = useMemo(() => {
    const list: AppNotification[] = [];

    assets.forEach((asset) => {
      // 1. High Risk / Critical AI Findings
      asset.findings.forEach((finding) => {
        // A finding is High Risk if severity is Critical or high confidence structural/moisture risk
        const isHighRisk =
          finding.severity === "Critical" ||
          (finding.conf >= 90 && finding.severity === "Moderate" && finding.type === "Moisture");

        if (isHighRisk && !finding.isResolved) {
          const notifId = `notif-finding-${asset.id}-${finding.id}`;
          list.push({
            id: notifId,
            type: "HIGH_RISK_FINDING",
            severity: "critical",
            title: `AI High-Risk Alert: ${finding.type} Detected (${finding.conf}% Conf)`,
            titleArabic: `تنبيه عالي الخطورة: رصد عيب إنشائي ${finding.type === "Crack" ? "تشقق" : "تسرب"} بنسبة ثقة ${finding.conf}%`,
            message: `Critical defect flagged in "${finding.area}". ${finding.description.slice(0, 95)}... SBC-304 compliance breach.`,
            messageArabic: `رصد عيب إنشائي حرج في منطقة "${finding.area}". يتطلب تدخلاً هندسياً فورياً لمعالجة متطلبات كود البناء السعودي.`,
            timestamp: finding.detectedAt || "Recent Inspection",
            read: readIds.has(notifId),
            assetId: asset.id,
            assetName: asset.name,
            assetNameArabic: asset.nameArabic,
            targetTab: "findings",
            targetFindingId: finding.id,
            metadata: {
              findingType: finding.type,
              severityLevel: finding.severity,
              sbcClause: finding.severity === "Critical" ? "SBC 304" : "SBC 201",
              confidence: finding.conf,
              area: finding.area,
            },
          });
        }
      });

      // 2. Action Items with Approaching Deadlines (or Overdue)
      // Standard SLA definitions for actions:
      const defaultDeadlines: Record<string, { hours: number; titleEn: string; titleAr: string; sbc: string; valSar: number }> = {
        "act-1": {
          hours: 3.5,
          titleEn: "Seal Roof MEP Condensation Drainage & Pooling",
          titleAr: "معالجة صرف تكثيف التكييف بالسطح ومنع تجمع المياه",
          sbc: "SBC 601",
          valSar: 180000,
        },
        "act-2": {
          hours: 5.2,
          titleEn: "Renew Parapet Polyurethane Expansion Joint Seal",
          titleAr: "تجديد فواصل تمدد السطح والسترة بمادة البولي يوريثان",
          sbc: "SBC 201",
          valSar: 120000,
        },
        "act-3": {
          hours: 8.0,
          titleEn: "Link Balady 2026 Digital Compliance Certificate",
          titleAr: "ربط شهادة الامتثال البلدي الرقمية 2026",
          sbc: "Municipal",
          valSar: 240000,
        },
      };

      asset.actions.forEach((action) => {
        if (!action.completed) {
          const deadlineData = defaultDeadlines[action.id] || {
            hours: 6.0,
            titleEn: action.action,
            titleAr: action.actionArabic,
            sbc: "SBC Standard",
            valSar: 95000,
          };

          const isApproaching = deadlineData.hours <= 24;
          if (isApproaching) {
            const notifId = `notif-action-${asset.id}-${action.id}`;
            const isCriticalDeadline = deadlineData.hours <= 4;

            list.push({
              id: notifId,
              type: "DEADLINE_APPROACHING",
              severity: isCriticalDeadline ? "critical" : "warning",
              title: `Urgent SLA Deadline: ${action.action}`,
              titleArabic: `اقتراب الموعد النهائي للإجراء: ${action.actionArabic}`,
              message: `Only ${deadlineData.hours}h remaining before SLA breach. Risk exposure: SAR ${deadlineData.valSar.toLocaleString()}.`,
              messageArabic: `متبقي ${deadlineData.hours} ساعات فقط قبل تجاوز المهلة المحددة (SLA). القيمة المعرضة للخطر: ${deadlineData.valSar.toLocaleString()} ريال.`,
              timestamp: `${deadlineData.hours}h remaining`,
              read: readIds.has(notifId),
              assetId: asset.id,
              assetName: asset.name,
              assetNameArabic: asset.nameArabic,
              targetTab: "actions",
              targetActionId: action.id,
              metadata: {
                hoursRemaining: deadlineData.hours,
                valueAtRiskSar: deadlineData.valSar,
                sbcClause: deadlineData.sbc,
                area: action.targetArea,
              },
            });
          }
        }
      });
    });

    return list;
  }, [assets, readIds]);

  // Merge auto-generated with simulated notifications, filtering out dismissed
  useEffect(() => {
    const combined = [...extraNotifications, ...autoGeneratedNotifications].filter(
      (n) => !dismissedIds.has(n.id)
    );

    // Sort by: unread first, then critical over warning
    combined.sort((a, b) => {
      if (a.read !== b.read) return a.read ? 1 : -1;
      if (a.severity === "critical" && b.severity !== "critical") return -1;
      if (b.severity === "critical" && a.severity !== "critical") return 1;
      return 0;
    });

    setNotifications(combined);
  }, [autoGeneratedNotifications, extraNotifications, dismissedIds]);

  // Counts
  const unreadCount = useMemo(() => {
    return notifications.filter((n) => !n.read).length;
  }, [notifications]);

  const highRiskCount = useMemo(() => {
    return notifications.filter((n) => n.type === "HIGH_RISK_FINDING" && !n.read).length;
  }, [notifications]);

  const approachingDeadlinesCount = useMemo(() => {
    return notifications.filter((n) => n.type === "DEADLINE_APPROACHING" && !n.read).length;
  }, [notifications]);

  // Persist dismissed IDs
  const dismissNotification = useCallback((id: string) => {
    setDismissedIds((prev) => {
      const next = new Set(prev).add(id);
      try {
        localStorage.setItem(STORAGE_KEY + "_dismissed", JSON.stringify(Array.from(next)));
      } catch {}
      return next;
    });
    setActiveToasts((prev) => prev.filter((t) => t.id !== id));
  }, []);

  // Mark as read
  const markAsRead = useCallback((id: string) => {
    setReadIds((prev) => {
      const next = new Set(prev).add(id);
      try {
        localStorage.setItem(STORAGE_KEY + "_read", JSON.stringify(Array.from(next)));
      } catch {}
      return next;
    });
  }, []);

  // Mark all as read
  const markAllAsRead = useCallback(() => {
    const allIds = notifications.map((n) => n.id);
    setReadIds((prev) => {
      const next = new Set([...prev, ...allIds]);
      try {
        localStorage.setItem(STORAGE_KEY + "_read", JSON.stringify(Array.from(next)));
      } catch {}
      return next;
    });
    setActiveToasts([]);
  }, [notifications]);

  // Clear all notifications (dismiss all)
  const clearAll = useCallback(() => {
    const allIds = notifications.map((n) => n.id);
    setDismissedIds((prev) => {
      const next = new Set([...prev, ...allIds]);
      try {
        localStorage.setItem(STORAGE_KEY + "_dismissed", JSON.stringify(Array.from(next)));
      } catch {}
      return next;
    });
    setActiveToasts([]);
  }, [notifications]);

  // Toggle audio
  const toggleSound = useCallback(() => {
    setSoundEnabled((prev) => {
      const next = !prev;
      try {
        localStorage.setItem(SOUND_KEY, JSON.stringify(next));
      } catch {}
      if (next) {
        playNotificationSound("info");
      }
      return next;
    });
  }, []);

  // Push an active toast
  const pushToast = useCallback(
    (notif: AppNotification) => {
      if (soundEnabled) {
        playNotificationSound(notif.severity);
      }
      setActiveToasts((prev) => [notif, ...prev.slice(0, 3)]);

      // Auto dismiss toast after 7 seconds
      setTimeout(() => {
        setActiveToasts((prev) => prev.filter((t) => t.id !== notif.id));
      }, 7000);
    },
    [soundEnabled]
  );

  const dismissToast = useCallback((id: string) => {
    setActiveToasts((prev) => prev.filter((t) => t.id !== id));
  }, []);

  // Handle clicking a notification to navigate directly to target
  const handleNavigateToNotification = useCallback(
    (notif: AppNotification) => {
      markAsRead(notif.id);
      dismissToast(notif.id);

      if (onSelectAsset && notif.assetId) {
        onSelectAsset(notif.assetId);
      }

      onNavigateTab(notif.targetTab);

      if (notif.targetFindingId && onHighlightFinding) {
        setTimeout(() => {
          onHighlightFinding(notif.targetFindingId!);
        }, 150);
      }
    },
    [markAsRead, dismissToast, onSelectAsset, onNavigateTab, onHighlightFinding]
  );

  // ── Simulator 1: Trigger Simulated High-Risk AI Finding Alert ──
  const simulateHighRiskFinding = useCallback(
    (activeAsset: AssetRecord) => {
      const newId = `sim-finding-${Date.now()}`;
      const simNotif: AppNotification = {
        id: newId,
        type: "HIGH_RISK_FINDING",
        severity: "critical",
        title: "⚡ LIVE AI DETECTION: Critical Structural Defect Detected",
        titleArabic: "⚡ رصد مباشر بالذكاء الاصطناعي: عيب إنشائي حرج (SBC-304)",
        message: `Computer Vision detected a 2.2mm shear tensile fracture on Main Structural Column C-04 with 96% AI confidence. Immediate shoring required.`,
        messageArabic: `رصدت خوارزميات الرؤية الحاسوبية شرخاً قصياً إنشائياً حرجاً بسعة 2.2 ملم على العمود الحامل C-04 بنسبة ثقة 96%. يتطلب دعماً إنشائياً عاجلاً.`,
        timestamp: "Just now (Live Alert)",
        read: false,
        assetId: activeAsset.id,
        assetName: activeAsset.name,
        assetNameArabic: activeAsset.nameArabic,
        targetTab: "findings",
        targetFindingId: 6,
        metadata: {
          findingType: "Crack",
          severityLevel: "Critical",
          sbcClause: "SBC 304 (Structural Concrete)",
          confidence: 96,
          area: "Ground Floor Main Column C-04",
        },
      };

      setExtraNotifications((prev) => [simNotif, ...prev]);
      pushToast(simNotif);
    },
    [pushToast]
  );

  // ── Simulator 2: Trigger Simulated Approaching Deadline Alert ──
  const simulateApproachingDeadline = useCallback(
    (activeAsset: AssetRecord) => {
      const newId = `sim-deadline-${Date.now()}`;
      const simNotif: AppNotification = {
        id: newId,
        type: "DEADLINE_APPROACHING",
        severity: "warning",
        title: "⏳ SLA EXPIRING SOON: 1.5 Hours Remaining on Municipal Escrow Seal",
        titleArabic: "⏳ اقتراب انتهاء المهلة: 1.5 ساعة متبقية لاعتماد الربط البلدي والضمان",
        message: `Action item 'Link Balady 2026 Digital Compliance Certificate' has only 90 minutes before municipal escrow penalty is enacted.`,
        messageArabic: `الإجراء 'ربط شهادة الامتثال البلدي 2026' متبقي له 90 دقيقة فقط قبل سريان تجميد إجراءات الإفراغ العقاري والضمان المالي.`,
        timestamp: "1.5h Remaining",
        read: false,
        assetId: activeAsset.id,
        assetName: activeAsset.name,
        assetNameArabic: activeAsset.nameArabic,
        targetTab: "actions",
        targetActionId: "act-3",
        metadata: {
          hoursRemaining: 1.5,
          valueAtRiskSar: 240000,
          sbcClause: "Municipal Governance",
          area: "Documentation & Portal Gateway",
        },
      };

      setExtraNotifications((prev) => [simNotif, ...prev]);
      pushToast(simNotif);
    },
    [pushToast]
  );

  return {
    notifications,
    unreadCount,
    highRiskCount,
    approachingDeadlinesCount,
    activeToasts,
    soundEnabled,
    toggleSound,
    markAsRead,
    markAllAsRead,
    dismissNotification,
    clearAll,
    dismissToast,
    handleNavigateToNotification,
    simulateHighRiskFinding,
    simulateApproachingDeadline,
  };
}
